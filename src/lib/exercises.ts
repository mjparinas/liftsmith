/**
 * The built-in exercises' text in the app's language. i18n.ts installs the lookup (`setExerciseText`);
 * this file doesn't import the catalogues itself, so the public website, which uses the library
 * without them, stays light and English. The keys are `ex.<id>`, `ex.<id>.setup` and `ex.<id>.cue1`
 * onwards (src/locales/text/ex.ts). A missing translation, or no lookup, reads the English row.
 */
let localise: ((key: string) => string | undefined) | null = null;
export function setExerciseText(lookup: ((key: string) => string | undefined) | null): void {
  localise = lookup;
}
const local = (key: string, english: string) => localise?.(key) ?? english;

const ENGLISH_NAME = new Map(ROWS.map((r) => [r[0], r[1]]));
/**
 * The English name, whatever the app's language: for matching names from other apps' CSV exports
 * and for tie-breaks that must not depend on the language (the generator stays reproducible).
 */
export function englishName(e: Pick<Exercise, "id" | "name">): string {
  return ENGLISH_NAME.get(e.id) ?? e.name;
}

export const EXERCISES: Exercise[] = ROWS.map(([id, name, primary, secondary, needs, load, pattern, start, setup, cues]) => ({
  id,
  get name() {
    return local(`ex.${id}`, name);
  },
  primary,
  secondary,
  needs,
  load,
  pattern,
  compound: pattern !== "isolation" && pattern !== "core" && (secondary.length > 0 || pattern === "carry"),
  start,
  get setup() {
    return local(`ex.${id}.setup`, setup);
  },
  get cues() {
    return cues.map((c, i) => local(`ex.${id}.cue${i + 1}`, c));
  },
}));

/** Each built-in exercise's English text, as written in ROWS (a test checks the catalogue matches). */
export const ENGLISH_ROWS: ReadonlyArray<{ id: string; name: string; setup: string; cues: readonly string[] }> = ROWS.map(
  ([id, name, , , , , , , setup, cues]) => ({ id, name, setup, cues }),
);

const BY_ID = new Map(EXERCISES.map((e) => [e.id, e]));
export const EXERCISE_BY_ID: ReadonlyMap<string, Exercise> = BY_ID;

const CUSTOM_NEEDS: Record<LoadKind, Equipment[]> = {
  barbell: ["barbell"],
  dumbbell: ["dumbbells"],
  kettlebell: ["kettlebells"],
  machine: [],
  bodyweight: [],
};
const CUSTOM_START: Record<LoadKind, number> = { barbell: 0.4, dumbbell: 0.12, kettlebell: 0.12, machine: 0.3, bodyweight: 0 };

/**
 * Adds the lifter's own exercises to the library (idempotent), so every screen, swap, stat and
 * export can look them up. Called when events load and when one is created.
 */
export function registerCustom(events: readonly AppEvent[]): void {
  for (const e of events) {
    if (e.type !== "customExercise" || BY_ID.has(e.exercise.id)) continue;
    const c = (e as CustomExerciseEvent).exercise;
    const ex: Exercise = {
      ...c,
      needs: CUSTOM_NEEDS[c.load],
      pattern: c.compound ? "core" : "isolation",
      start: CUSTOM_START[c.load],
      setup: "Your own exercise.",
      cues: ["Set it up the way you usually do", "Control every rep"],
      custom: true,
    };
    if (c.compound)
      ex.pattern = c.primary.some((m) => ["quads", "glutes"].includes(m))
        ? "squat"
        : c.primary.some((m) => ["lats", "upperBack"].includes(m))
          ? "hpull"
          : c.primary.some((m) => ["chest", "frontDelts", "triceps"].includes(m))
            ? "hpush"
            : "hinge";
    EXERCISES.push(ex);
    BY_ID.set(ex.id, ex);
  }
}
/**
 * Steps of the calisthenics skill ladders (programs.ts). They make sense as a step on the way to a
 * harder movement, not as a pick of their own, so the adaptive generator leaves them out.
 */
export const LADDER_ONLY: ReadonlySet<string> = new Set([
  "scapular-pull",
  "negative-pull-up",
  "negative-dip",
  "wall-push-up",
  "pseudo-planche-push-up",
  "shrimp-squat",
  "pistol-squat",
]);

export function exercise(id: string): Exercise {
  const e = EXERCISE_BY_ID.get(id);
  if (!e) throw new Error(`Unknown exercise ${id}`);
  return e;
}

/** Exercises the gym can do: every needed item is there. */
export function available(gymEquipment: readonly string[], list: readonly Exercise[] = EXERCISES): Exercise[] {
  const have = new Set(gymEquipment);
  return list.filter((e) => e.needs.every((n) => have.has(n)));
}
